#!/usr/bin/env python3
"""Turn official-image-ports.json into Sources/NoodleEngine/Names/OfficialImagePorts.swift.

Reads that JSON and nothing else. Run: python3 -I docs/provenance/gen-official-image-ports.py
Ranking: web-class ports by descending image count, ties by ascending port number; not-web
ports are a separate class, ordered the same way.
"""
import json
from pathlib import Path

here = Path(__file__).resolve().parent
doc = json.loads((here / "official-image-ports.json").read_text())
counts = {int(p): n for p, n in doc["portCounts"].items()}
classes = {int(p): c for p, c in doc["portClass"].items()}

def ordered(kind):
    ports = [p for p in counts if classes[p] == kind]
    return sorted(ports, key=lambda p: (-counts[p], p))

rows = []
for kind, swift in (("web", ".web"), ("notweb", ".notWeb")):
    for rank, p in enumerate(ordered(kind)):
        rank_arg = f", rank: {rank}" if kind == "web" else ""  # only web ranks are read
        rows.append(f"        {p}: Entry(kind: {swift}{rank_arg}),")

out = f"""// GENERATED by docs/provenance/gen-official-image-ports.py from docs/provenance/official-image-ports.json.
// Do not edit by hand; rerun the generator. Data retrieved {doc["retrieved"]}.
//
// Method: the {doc["topN"]} most-pulled Docker Official Images were read from Docker Hub's public API, and the
// ExposedPorts of each one's image config were counted (images per port). An image is not-web when Hub
// files it under {", ".join(doc["notWebCategories"])} (or, with no category, when its name matches a
// database or broker word). A port is web-class when at least one web image exposes it. Within a class the
// rank is the position by descending image count, ties by ascending port.

enum OfficialImagePorts {{
    enum PortClass: Sendable {{ case web, notWeb }}

    struct Entry: Sendable {{
        let kind: PortClass
        /// 0 is the most web-typical web port. Not-web ports carry no rank.
        var rank = 0
    }}

    static let table: [Int: Entry] = [
{chr(10).join(rows)}
    ]
}}
"""
(here.parent.parent / "Sources/NoodleEngine/Names/OfficialImagePorts.swift").write_text(out)
print("wrote OfficialImagePorts.swift with", len(rows), "ports")
